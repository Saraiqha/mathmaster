                    <span class="lang-en">a &gt; 0 (∪ shape)</span>
                    <span class="lang-bm hidden">a &gt; 0 (bentuk ∪)</span>
                </p>
                <p class="text-2xl mb-1">∪</p>
                <p class="text-xs text-slate-500">
                    <span class="lang-en">Roots are where the bottom of ∪ crosses the x-axis</span>
                    <span class="lang-bm hidden">Punca ialah di mana bahagian bawah ∪ menyilang paksi-x</span>
                </p>
            </div>
