                <span class="lang-bm hidden">📌 Apakah punca?</span>
            </p>
            <p class="text-sm text-slate-600 lang-en">Roots are the <strong>values of x that satisfy the equation</strong>. On a graph, roots are the <strong>x-coordinates where the parabola crosses the x-axis</strong> (also called x-intercepts).</p>
            <p class="text-sm text-slate-600 lang-bm hidden">Punca ialah <strong>nilai x yang memenuhi persamaan</strong>. Pada graf, punca ialah <strong>koordinat-x di mana parabola menyilang paksi-x</strong> (juga dipanggil pintasan-x).</p>
