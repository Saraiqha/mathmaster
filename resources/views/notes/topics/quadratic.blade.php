                    <span class="lang-en">Roots are where the sides of ∩ cross the x-axis</span>
                    <span class="lang-bm hidden">Punca ialah di mana sisi ∩ menyilang paksi-x</span>
                </p>
            </div>
        </div>

        <p class="text-xs font-bold text-slate-600 mb-3">
            <span class="lang-en">Methods to find roots:</span>
            <span class="lang-bm hidden">Kaedah mencari punca:</span>
        </p>
        <div class="grid grid-cols-2 gap-3">
            <div class="p-4 bg-sky-50 rounded-xl border border-sky-100">
                <p class="text-xs font-bold text-sky-700 mb-2">
                    <span class="lang-en">(a) Factorisation Method</span>
                    <span class="lang-bm hidden">(a) Kaedah Pemfaktoran</span>
                </p>
                <p class="text-xs text-slate-600 lang-en">For x² + bx + c = 0: find two numbers p and q where <strong>p × q = c</strong> and <strong>p + q = b</strong>. Then (x + p)(x + q) = 0, so x = -p or x = -q.</p>
                <p class="text-xs text-slate-600 lang-bm hidden">Untuk x² + bx + c = 0: cari dua nombor p dan q di mana <strong>p × q = c</strong> dan <strong>p + q = b</strong>. Maka (x + p)(x + q) = 0, jadi x = -p atau x = -q.</p>
            </div>
            <div class="p-4 bg-violet-50 rounded-xl border border-violet-100">
                <p class="text-xs font-bold text-violet-700 mb-2">
                    <span class="lang-en">(b) Graphical Method</span>
                    <span class="lang-bm hidden">(b) Kaedah Grafik</span>
                </p>
                <p class="text-xs text-slate-600 lang-en">Plot the graph of f(x) = ax² + bx + c. The roots are the <strong>x-coordinates of the points where the graph crosses the x-axis</strong>.</p>
                <p class="text-xs text-slate-600 lang-bm hidden">Plot graf f(x) = ax² + bx + c. Punca ialah <strong>koordinat-x titik di mana graf menyilang paksi-x</strong>.</p>
            </div>
