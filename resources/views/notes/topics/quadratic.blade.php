{{-- 4. Common Mistakes --}}
<div class="bg-rose-50 border border-rose-100 rounded-2xl p-6 mb-4 shadow-sm">
    <h4 class="text-sm font-bold text-rose-700 mb-4">
        <span class="lang-en">⚠️ Common Mistakes to Avoid</span>
        <span class="lang-bm hidden">⚠️ Kesilapan Lazim yang Perlu Dielakkan</span>
    </h4>
    <div class="space-y-3">
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Saying a = 0 is allowed</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Mengatakan a = 0 dibenarkan</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">If a = 0, there is no x² term — it becomes a linear function f(x) = bx + c, NOT quadratic.</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Jika a = 0, tiada sebutan x² — ia menjadi fungsi linear f(x) = bx + c, BUKAN kuadratik.</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Confusing axis of symmetry position for b values</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Keliru tentang kedudukan paksi simetri untuk nilai b</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">Remember: b &lt; 0 → axis is RIGHT (x &gt; 0), b &gt; 0 → axis is LEFT (x &lt; 0). This applies for both a &gt; 0 and a &lt; 0.</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Ingat: b &lt; 0 → paksi di KANAN (x &gt; 0), b &gt; 0 → paksi di KIRI (x &lt; 0). Ini terpakai untuk a &gt; 0 dan a &lt; 0.</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Thinking minimum/maximum is the same as axis of symmetry</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Menganggap minimum/maksimum sama dengan paksi simetri</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">Axis of symmetry x = h is a LINE. Vertex (h, k) is a POINT. They share the same x-value but are different things.</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Paksi simetri x = h adalah GARIS. Bucu (h, k) adalah TITIK. Mereka berkongsi nilai x yang sama tetapi adalah perkara berbeza.</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Wrong sign when using factorisation</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Tanda yang salah semasa menggunakan pemfaktoran</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">If (x − 2)(x − 3) = 0, then x = +2 or x = +3. NOT x = −2 or x = −3. The sign flips!</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Jika (x − 2)(x − 3) = 0, maka x = +2 atau x = +3. BUKAN x = −2 atau x = −3. Tandanya bertukar!</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Forgetting to divide through before factorising</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Terlupa membahagi terlebih dahulu sebelum memfaktorkan</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">For 2x² − 8x + 6 = 0, divide by 2 first to get x² − 4x + 3 = 0, then factorise. Much easier!</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Untuk 2x² − 8x + 6 = 0, bahagi dengan 2 dahulu untuk mendapat x² − 4x + 3 = 0, kemudian faktorkan. Lebih mudah!</p>
            </div>
        </div>
