                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">General form:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Bentuk umum:</p>
                            <p class="text-slate-600 lang-en">Premise 1: All A is B</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Semua A ialah B</p>
                            <p class="text-slate-600 lang-en">Premise 2: C is A</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: C ialah A</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: C is B</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: C ialah B</p>
                        </div>
                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">Example:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Contoh:</p>
                            <p class="text-slate-600 lang-en">Premise 1: All multiples of 6 are multiples of 3</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Semua gandaan 6 ialah gandaan 3</p>
                            <p class="text-slate-600 lang-en">Premise 2: 18 is a multiple of 6</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: 18 ialah gandaan 6</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: 18 is a multiple of 3</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: 18 ialah gandaan 3</p>
                        </div>
                    </div>
                </div>

                {{-- Form 2 --}}
                <div class="p-3 bg-white rounded-lg border border-violet-100">
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-en">Form 2 — Modus Ponens (If p then q, p is true → q is true)</p>
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-bm hidden">Bentuk 2 — Modus Ponen (Jika p maka q, p benar → q benar)</p>
                    <div class="grid grid-cols-2 gap-2 text-xs">
                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">General form:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Bentuk umum:</p>
                            <p class="text-slate-600 lang-en">Premise 1: If p, then q</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Jika p, maka q</p>
                            <p class="text-slate-600 lang-en">Premise 2: p is true</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: p adalah benar</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: q is true</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: q adalah benar</p>
                        </div>
                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">Example:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Contoh:</p>
                            <p class="text-slate-600 lang-en">Premise 1: If x is a multiple of 6, then x is a multiple of 3</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Jika x ialah gandaan 6, maka x ialah gandaan 3</p>
                            <p class="text-slate-600 lang-en">Premise 2: 18 is a multiple of 6</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: 18 ialah gandaan 6</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: 18 is a multiple of 3</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: 18 ialah gandaan 3</p>
                        </div>
                    </div>
                </div>

                {{-- Form 3 --}}
                <div class="p-3 bg-white rounded-lg border border-violet-100">
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-en">Form 3 — Modus Tollens (If p then q, not q → not p)</p>
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-bm hidden">Bentuk 3 — Modus Tolens (Jika p maka q, bukan q → bukan p)</p>
                    <div class="grid grid-cols-2 gap-2 text-xs">
                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">General form:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Bentuk umum:</p>
                            <p class="text-slate-600 lang-en">Premise 1: If p, then q</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Jika p, maka q</p>
                            <p class="text-slate-600 lang-en">Premise 2: Not q is true</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: Bukan q adalah benar</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: Not p is true</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: Bukan p adalah benar</p>
                        </div>
                        <div>
                            <p class="font-bold text-slate-600 mb-1 lang-en">Example:</p>
                            <p class="font-bold text-slate-600 mb-1 lang-bm hidden">Contoh:</p>
                            <p class="text-slate-600 lang-en">Premise 1: If x is a multiple of 6, then x is a multiple of 3</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 1: Jika x ialah gandaan 6, maka x ialah gandaan 3</p>
                            <p class="text-slate-600 lang-en">Premise 2: 17 is NOT a multiple of 3</p>
                            <p class="text-slate-600 lang-bm hidden">Premis 2: 17 BUKAN gandaan 3</p>
                            <p class="font-bold text-violet-700 lang-en">Conclusion: 17 is NOT a multiple of 6</p>
                            <p class="font-bold text-violet-700 lang-bm hidden">Kesimpulan: 17 BUKAN gandaan 6</p>
                        </div>
                    </div>
