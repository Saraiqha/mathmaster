{{-- 4. Common Mistakes --}}
<div class="bg-rose-50 border border-rose-100 rounded-2xl p-6 mb-4 shadow-sm">
    <h4 class="text-sm font-bold text-rose-700 mb-4">
        <span class="lang-en">⚠️ Common Mistakes to Avoid</span>
        <span class="lang-bm hidden">⚠️ Kesilapan Lazim yang Perlu Dielakkan</span>
    </h4>
    <div class="space-y-3">
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Thinking p→q is False when p is False</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Menganggap p→q Palsu apabila p Palsu</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">p→q is ONLY False when p=True AND q=False. When p is False, the implication is ALWAYS True regardless of q!</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">p→q hanya Palsu apabila p=Benar DAN q=Palsu. Apabila p Palsu, implikasi SENTIASA Benar tanpa mengira q!</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Confusing converse and contrapositive</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Keliru antara konvers dan kontrapositif</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">Converse = just swap (q→p). Contrapositive = swap AND negate (~q→~p). Only contrapositive is equivalent to original!</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Konvers = tukar sahaja (q→p). Kontrapositif = tukar DAN nafikan (~q→~p). Hanya kontrapositif yang setara dengan asal!</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Using wrong deductive argument form</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Menggunakan bentuk hujah deduktif yang salah</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">Check carefully: Form 1 uses "All A is B". Form 2 (Modus Ponens) — p is true, conclude q. Form 3 (Modus Tollens) — not q is true, conclude not p.</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Semak dengan teliti: Bentuk 1 menggunakan "Semua A ialah B". Bentuk 2 (Modus Ponen) — p benar, simpul q. Bentuk 3 (Modus Tolens) — bukan q benar, simpul bukan p.</p>
            </div>
        </div>
        <div class="flex gap-3">
            <span class="text-rose-400 flex-shrink-0 font-bold">✗</span>
            <div>
                <p class="text-sm font-semibold text-slate-700 lang-en">Saying questions and commands are statements</p>
                <p class="text-sm font-semibold text-slate-700 lang-bm hidden">Mengatakan soalan dan arahan adalah pernyataan</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-en">A statement must be decidable as True or False. "Is 5 odd?" cannot be True or False — it is a question, NOT a statement.</p>
                <p class="text-xs text-slate-500 mt-0.5 lang-bm hidden">Pernyataan mesti boleh diputuskan sebagai Benar atau Palsu. "Adakah 5 ganjil?" tidak boleh Benar atau Palsu — ia adalah soalan, BUKAN pernyataan.</p>
            </div>
