        {{-- Compound Statements --}}
        <div class="p-4 bg-sky-50 rounded-xl border border-sky-100 mb-4">
            <p class="text-xs font-bold text-sky-700 mb-3 lang-en">📌 Compound Statements — "or" and "and"</p>
            <p class="text-xs font-bold text-sky-700 mb-3 lang-bm hidden">📌 Pernyataan Majmuk — "atau" dan "dan"</p>
            <div class="grid grid-cols-2 gap-3">
                <div class="p-3 bg-white rounded-lg border border-sky-100">
                    <p class="text-xs font-bold text-sky-600 mb-2 lang-en">p OR q (Disjunction)</p>
                    <p class="text-xs font-bold text-sky-600 mb-2 lang-bm hidden">p ATAU q (Disjungsi)</p>
                    <p class="text-xs text-slate-600 lang-en">TRUE when <strong>at least one</strong> of p or q is True</p>
                    <p class="text-xs text-slate-600 lang-bm hidden">BENAR apabila <strong>sekurang-kurangnya satu</strong> daripada p atau q adalah Benar</p>
                    <div class="mt-2 text-xs font-mono space-y-1">
                        <p>T OR T = <strong class="text-teal-600">T</strong></p>
                        <p>T OR F = <strong class="text-teal-600">T</strong></p>
                        <p>F OR T = <strong class="text-teal-600">T</strong></p>
                        <p>F OR F = <strong class="text-rose-600">F</strong></p>
                    </div>
                </div>
                <div class="p-3 bg-white rounded-lg border border-sky-100">
                    <p class="text-xs font-bold text-sky-600 mb-2 lang-en">p AND q (Conjunction)</p>
                    <p class="text-xs font-bold text-sky-600 mb-2 lang-bm hidden">p DAN q (Konjungsi)</p>
                    <p class="text-xs text-slate-600 lang-en">TRUE only when <strong>BOTH</strong> p and q are True</p>
                    <p class="text-xs text-slate-600 lang-bm hidden">BENAR hanya apabila <strong>KEDUA-DUA</strong> p dan q adalah Benar</p>
                    <div class="mt-2 text-xs font-mono space-y-1">
                        <p>T AND T = <strong class="text-teal-600">T</strong></p>
                        <p>T AND F = <strong class="text-rose-600">F</strong></p>
                        <p>F AND T = <strong class="text-rose-600">F</strong></p>
                        <p>F AND F = <strong class="text-rose-600">F</strong></p>
                    </div>
                </div>
            </div>
            <div class="mt-3 p-3 bg-white rounded-lg border border-sky-100">
                <p class="text-xs font-bold text-slate-600 mb-1 lang-en">Example: p: 12 is a multiple of 5 (False), q: 12 is a multiple of 6 (True)</p>
                <p class="text-xs font-bold text-slate-600 mb-1 lang-bm hidden">Contoh: p: 12 ialah gandaan 5 (Palsu), q: 12 ialah gandaan 6 (Benar)</p>
                <p class="text-xs text-slate-600 lang-en">• p OR q: 12 is a multiple of 5 <strong>or</strong> 12 is a multiple of 6 → F OR T = <strong class="text-teal-600">True</strong></p>
                <p class="text-xs text-slate-600 lang-bm hidden">• p ATAU q: 12 ialah gandaan 5 <strong>atau</strong> 12 ialah gandaan 6 → P ATAU B = <strong class="text-teal-600">Benar</strong></p>
                <p class="text-xs text-slate-600 lang-en">• p AND q: 12 is a multiple of 5 <strong>and</strong> 12 is a multiple of 6 → F AND T = <strong class="text-rose-600">False</strong></p>
                <p class="text-xs text-slate-600 lang-bm hidden">• p DAN q: 12 ialah gandaan 5 <strong>dan</strong> 12 ialah gandaan 6 → P DAN B = <strong class="text-rose-600">Palsu</strong></p>
            </div>
        </div>

        {{-- Implication --}}
        <div class="p-4 bg-violet-50 rounded-xl border border-violet-100 mb-4">
            <p class="text-xs font-bold text-violet-700 mb-3 lang-en">📌 Implication — "If p, then q" written as p→q</p>
            <p class="text-xs font-bold text-violet-700 mb-3 lang-bm hidden">📌 Implikasi — "Jika p, maka q" ditulis sebagai p→q</p>
            <div class="grid grid-cols-2 gap-3 mb-3">
                <div class="p-3 bg-white rounded-lg border border-violet-100">
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-en">Truth table for p→q</p>
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-bm hidden">Jadual kebenaran p→q</p>
                    <div class="text-xs font-mono space-y-1">
                        <p>T → T = <strong class="text-teal-600">T</strong></p>
                        <p>T → F = <strong class="text-rose-600">F</strong> ← <span class="lang-en">only false case!</span><span class="lang-bm hidden">satu-satunya kes palsu!</span></p>
                        <p>F → T = <strong class="text-teal-600">T</strong></p>
                        <p>F → F = <strong class="text-teal-600">T</strong></p>
                    </div>
                </div>
                <div class="p-3 bg-white rounded-lg border border-violet-100">
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-en">Key rule to remember</p>
                    <p class="text-xs font-bold text-violet-600 mb-2 lang-bm hidden">Peraturan utama untuk diingat</p>
                    <p class="text-xs text-slate-600 lang-en">p→q is <strong>FALSE only when p is True AND q is False</strong>. In all other cases it is TRUE — even when p is False!</p>
                    <p class="text-xs text-slate-600 lang-bm hidden">p→q adalah <strong>PALSU hanya apabila p Benar DAN q Palsu</strong>. Dalam semua kes lain ia BENAR — walaupun p adalah Palsu!</p>
                </div>
            </div>
            <div class="p-3 bg-white rounded-lg border border-violet-100">
                <p class="text-xs font-bold text-slate-600 mb-2 lang-en">Also: "p if and only if q" (biconditional) — True when BOTH have same truth value</p>
                <p class="text-xs font-bold text-slate-600 mb-2 lang-bm hidden">Juga: "p jika dan hanya jika q" (bikondisional) — Benar apabila KEDUA-DUA mempunyai nilai kebenaran yang sama</p>
                <p class="text-xs text-slate-500 lang-en">T ↔ T = True | T ↔ F = False | F ↔ T = False | F ↔ F = True</p>
                <p class="text-xs text-slate-500 lang-bm hidden">B ↔ B = Benar | B ↔ P = Palsu | P ↔ B = Palsu | P ↔ P = Benar</p>
            </div>
        </div>

