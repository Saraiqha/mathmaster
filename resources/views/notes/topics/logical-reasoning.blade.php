    <div class="mb-6">
        <div class="flex items-center gap-2 mb-3">
            <div class="w-2 h-2 bg-teal-500 rounded-full"></div>
            <p class="text-sm font-bold text-slate-700">
                <span class="lang-en">A. Statements — True or False</span>
                <span class="lang-bm hidden">A. Pernyataan — Benar atau Palsu</span>
            </p>
        </div>

        <div class="p-4 bg-teal-50 rounded-xl border border-teal-100 mb-3">
            <p class="text-xs font-bold text-teal-700 mb-2 lang-en">📌 What is a statement?</p>
            <p class="text-xs font-bold text-teal-700 mb-2 lang-bm hidden">📌 Apakah pernyataan?</p>
            <p class="text-sm text-slate-700 lang-en">A statement is a sentence that is <strong>either TRUE or FALSE</strong>, but not both at the same time.</p>
            <p class="text-sm text-slate-700 lang-bm hidden">Pernyataan ialah ayat yang <strong>sama ada BENAR atau PALSU</strong>, tetapi tidak kedua-duanya pada masa yang sama.</p>
        </div>

        <div class="grid grid-cols-2 gap-3 mb-4">
            <div class="p-3 bg-teal-50 rounded-xl border border-teal-100">
                <p class="text-xs font-bold text-teal-700 mb-2 lang-en">✅ IS a statement</p>
                <p class="text-xs font-bold text-teal-700 mb-2 lang-bm hidden">✅ ADALAH pernyataan</p>
                <ul class="space-y-1 text-xs text-slate-600">
                    <li class="lang-en">• 12 is a multiple of 5 (False)</li>
                    <li class="lang-bm hidden">• 12 ialah gandaan 5 (Palsu)</li>
                    <li class="lang-en">• 5 + 3 = 8 (True)</li>
                    <li class="lang-bm hidden">• 5 + 3 = 8 (Benar)</li>
                    <li class="lang-en">• All cats are black (False)</li>
                    <li class="lang-bm hidden">• Semua kucing berwarna hitam (Palsu)</li>
                    <li class="lang-en">• Kuala Lumpur is in Malaysia (True)</li>
                    <li class="lang-bm hidden">• Kuala Lumpur berada di Malaysia (Benar)</li>
                </ul>
            </div>
            <div class="p-3 bg-rose-50 rounded-xl border border-rose-100">
